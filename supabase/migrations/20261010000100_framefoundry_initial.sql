create function public.reorder_portfolio_projects(project_ids bigint[])
returns boolean
language plpgsql
security invoker
set search_path = ''
as $$
declare
  owned_count integer;
  requested_count integer;
  project_id bigint;
  project_index integer;
begin
  select count(*) into owned_count
  from public.portfolio_projects pp
  join public.creator_profiles cp on cp.id = pp.creator_id
  where cp.user_id = (select auth.uid());

  requested_count := coalesce(cardinality(project_ids), 0);
  if requested_count <> owned_count then return false; end if;
  if (select count(distinct id) from unnest(project_ids) as ids(id)) <> requested_count then return false; end if;
  if exists (
    select id from unnest(project_ids) as ids(id)
    except
    select pp.id from public.portfolio_projects pp
    join public.creator_profiles cp on cp.id = pp.creator_id
    where cp.user_id = (select auth.uid())
  ) then return false; end if;

  project_index := 0;
  foreach project_id in array project_ids loop
    update public.portfolio_projects pp
    set sort_order = project_index
    from public.creator_profiles cp
    where pp.id = project_id and cp.id = pp.creator_id
      and cp.user_id = (select auth.uid());
    project_index := project_index + 1;
  end loop;
  return true;
end;
$$;

grant execute on function public.reorder_portfolio_projects(bigint[]) to authenticated;
revoke all on function public.reorder_portfolio_projects(bigint[]) from public, anon;
