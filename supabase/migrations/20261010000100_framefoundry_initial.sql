create function public.create_profile_for_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, display_name)
  values (new.id, nullif(new.raw_user_meta_data ->> 'name', ''))
  on conflict (id) do nothing;
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.create_profile_for_auth_user();

create function public.enforce_brief_status_transition()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.status = old.status then return new; end if;
  if old.status = 'draft' and new.status = 'published' then return new; end if;
  if old.status = 'published' and new.status in ('draft', 'closed') then return new; end if;
  raise exception 'Invalid brief status transition: % -> %', old.status, new.status
    using errcode = '23514';
end;
$$;

create trigger briefs_valid_status_transition
  before update of status on public.briefs
  for each row execute function public.enforce_brief_status_transition();

create function public.enforce_collaboration_status_transition()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.status = old.status then return new; end if;
  if old.status = 'sent' and new.status in ('accepted', 'declined') then return new; end if;
  raise exception 'Invalid collaboration status transition: % -> %', old.status, new.status
    using errcode = '23514';
end;
$$;

create trigger collaboration_valid_status_transition
  before update of status on public.collaboration_requests
  for each row execute function public.enforce_collaboration_status_transition();

