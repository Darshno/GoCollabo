create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  account_type text not null default 'creator'
    check (account_type in ('creator', 'brand')),
  display_name text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.creator_profiles (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references public.profiles (id) on delete cascade,
  slug text not null unique,
  name text not null,
  headline text not null,
  bio text not null,
  location text not null,
  work_mode text not null check (work_mode in ('remote', 'hybrid', 'on-site')),
  skills text not null default '',
  tools text not null default '',
  content_types text not null default '',
  styles text not null default '',
  experience text not null default '',
  rates text,
  formats text not null default '',
  workflow text not null default '',
  verification_status text not null default 'self-reported'
    check (verification_status in ('self-reported', 'not-verified')),
  availability text not null default 'available'
    check (availability in ('available', 'selective', 'unavailable')),
  published boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index creator_profiles_published_updated_idx
  on public.creator_profiles (updated_at desc) where published;

create table public.portfolio_projects (
  id bigint generated by default as identity primary key,
  creator_id bigint not null references public.creator_profiles (id) on delete cascade,
  title text not null,
  description text not null default '',
  content_type text not null default '',
  tools text not null default '',
  skills text not null default '',
  role text not null default '',
  challenge text not null default '',
  approach text not null default '',
  outcomes text not null default '',
  impact_summary text not null default '',
  media_path text,
  media_name text,
  media_type text check (media_type is null or media_type in ('image/jpeg', 'image/png', 'image/webp', 'image/gif')),
  media_size integer check (media_size is null or media_size between 1 and 8388608),
  is_concept boolean not null default false,
  published boolean not null default false,
  sort_order integer not null default 0 check (sort_order >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check ((media_path is null) = (media_name is null)),
  check ((media_path is null) = (media_type is null)),
  check ((media_path is null) = (media_size is null))
);

create index portfolio_projects_creator_order_idx
  on public.portfolio_projects (creator_id, sort_order, created_at desc);
create index portfolio_projects_public_idx
  on public.portfolio_projects (creator_id, sort_order) where published;

create table public.briefs (
