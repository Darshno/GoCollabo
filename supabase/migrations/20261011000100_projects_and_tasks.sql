-- 3. Policies for project_deliverables
create policy project_deliverables_participant_read on public.project_deliverables
  for select to authenticated using (
    exists (
      select 1 from public.projects p
      where p.id = project_id and (
        p.brand_id = (select auth.uid()) or exists (
          select 1 from public.creator_profiles cp
          where cp.id = p.creator_id and cp.user_id = (select auth.uid())
        )
      )
    )
  );

-- Only creator participant can submit deliverables
create policy project_deliverables_creator_insert on public.project_deliverables
  for insert to authenticated with check (
    exists (
      select 1 from public.projects p
      join public.creator_profiles cp on cp.id = p.creator_id
      where p.id = project_id and cp.user_id = (select auth.uid())
    )
  );

-- Only brand participant can review / update deliverables
create policy project_deliverables_brand_update on public.project_deliverables
  for update to authenticated using (
    exists (
      select 1 from public.projects p
      where p.id = project_id and p.brand_id = (select auth.uid())
    )
  ) with check (
    exists (
      select 1 from public.projects p
      where p.id = project_id and p.brand_id = (select auth.uid())
    )
  );

-- Grants
grant select, insert, update on public.projects to authenticated;
grant select, insert, update on public.project_tasks to authenticated;
grant select, insert, update on public.project_deliverables to authenticated;

-- Atomic project & initial tasks creation procedure
-- SECURITY DEFINER: runs as function owner. All security checks must be enforced explicitly.
create or replace function public.create_project_with_tasks(
  p_request_id bigint,
  p_brief_id   bigint,
  p_brand_id   uuid,
  p_creator_id bigint,
  p_tasks      jsonb
) returns bigint as $$
declare
  v_project_id    bigint;
  v_task          jsonb;
  v_caller_id     uuid;
  v_req_brand_id  uuid;
  v_req_creator_id bigint;
  v_req_status    text;
begin
  -- 1. Require an authenticated caller.
  v_caller_id := auth.uid();
  if v_caller_id is null then
    raise exception 'authentication required'
      using errcode = '42501';
  end if;

  -- 2. Validate the collaboration request: must exist and be accepted.
  select cr.brand_id, cr.creator_id, cr.status
    into v_req_brand_id, v_req_creator_id, v_req_status
    from public.collaboration_requests cr
   where cr.id = p_request_id;

  if not found then
    raise exception 'collaboration request % not found', p_request_id
      using errcode = 'P0002';
  end if;

  if v_req_status <> 'accepted' then
    raise exception 'collaboration request % is not in accepted status (got: %)',
      p_request_id, v_req_status
      using errcode = '23514';
  end if;

  -- 3. Reject parameter tampering: provided IDs must match the request.
  if p_brand_id <> v_req_brand_id or p_creator_id <> v_req_creator_id then
    raise exception 'participant IDs do not match collaboration request %', p_request_id
      using errcode = '23514';
  end if;

  -- 4. Caller must be the brand or the creator participant.
  if v_caller_id <> v_req_brand_id then
    if not exists (
      select 1 from public.creator_profiles cp
       where cp.id = v_req_creator_id
         and cp.user_id = v_caller_id
    ) then
      raise exception 'caller is not an authorized participant of request %', p_request_id
        using errcode = '42501';
    end if;
  end if;

  -- 5. Idempotency: if project already exists for this request, return its id.
  select id into v_project_id
    from public.projects
   where request_id = p_request_id;
  if found then
    return v_project_id;
  end if;

  -- 6. Insert project — let the identity sequence generate the primary key.
  insert into public.projects (request_id, brief_id, brand_id, creator_id, status)
  values (p_request_id, p_brief_id, p_brand_id, p_creator_id, 'active')
  returning id into v_project_id;

  -- 7. Insert tasks atomically in the same transaction.
  for v_task in select * from jsonb_array_elements(p_tasks)
  loop
    insert into public.project_tasks (id, project_id, title, description, status, priority, deadline, source)
    values (
      v_task->>'id',
      v_project_id,
      v_task->>'title',
      coalesce(v_task->>'description', ''),
      coalesce(v_task->>'status', 'todo'),
      coalesce(v_task->>'priority', 'medium'),
      v_task->>'deadline',
      coalesce(v_task->>'source', 'brief')
    );
  end loop;

  return v_project_id;
end;
$$ language plpgsql security definer;

grant execute on function public.create_project_with_tasks(bigint, bigint, uuid, bigint, jsonb) to authenticated;
