-- FrameFoundry / GoCollabo: Shared Projects, Tasks, and Deliverables Schema
-- Extends the initial marketplace schema with persistent project collaboration tables and complete RLS policies.

create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  request_id bigint not null references public.collaboration_requests (id) on delete cascade,
  brief_id bigint not null references public.briefs (id) on delete cascade,
  brand_id uuid not null references public.profiles (id) on delete cascade,
  creator_id bigint not null references public.creator_profiles (id) on delete cascade,
  status text not null default 'active' check (status in ('active', 'in_review', 'completed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (request_id)
);

create index if not exists projects_brand_idx on public.projects (brand_id, updated_at desc);
create index if not exists projects_creator_idx on public.projects (creator_id, updated_at desc);

create table if not exists public.project_tasks (
  id text primary key,
  project_id bigint not null references public.projects (id) on delete cascade,
  title text not null,
  description text not null default '',
  status text not null default 'todo' check (status in ('todo', 'in_progress', 'done')),
  priority text not null default 'medium' check (priority in ('high', 'medium', 'low')),
  deadline text,
  source text not null default 'manual' check (source in ('brief', 'manual', 'ai_copilot')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists project_tasks_project_idx on public.project_tasks (project_id);

create table if not exists public.project_deliverables (
  id text primary key,
  project_id bigint not null references public.projects (id) on delete cascade,
  version integer not null,
  title text not null,
  notes text not null default '',
  asset_url text,
  status text not null default 'pending_review' check (status in ('pending_review', 'changes_requested', 'approved')),
  feedback text,
  submitted_at timestamptz not null default now(),
  reviewed_at timestamptz
);

create index if not exists project_deliverables_project_idx on public.project_deliverables (project_id, version desc);

-- RLS: Enabled for all project tables
alter table public.projects enable row level security;
alter table public.project_tasks enable row level security;
alter table public.project_deliverables enable row level security;

-- Drop existing policies if re-applying to prevent conflicts
drop policy if exists projects_participant_read on public.projects;
drop policy if exists projects_participant_insert on public.projects;
drop policy if exists projects_participant_update on public.projects;

drop policy if exists project_tasks_participant_read on public.project_tasks;
drop policy if exists project_tasks_participant_insert on public.project_tasks;
drop policy if exists project_tasks_participant_update on public.project_tasks;

drop policy if exists project_deliverables_participant_read on public.project_deliverables;
drop policy if exists project_deliverables_creator_insert on public.project_deliverables;
drop policy if exists project_deliverables_brand_update on public.project_deliverables;

-- 1. Policies for projects
create policy projects_participant_read on public.projects
  for select to authenticated using (
    brand_id = (select auth.uid()) or exists (
      select 1 from public.creator_profiles cp
      where cp.id = creator_id and cp.user_id = (select auth.uid())
    )
  );

create policy projects_participant_insert on public.projects
  for insert to authenticated with check (
    (brand_id = (select auth.uid()) or exists (
      select 1 from public.creator_profiles cp
      where cp.id = creator_id and cp.user_id = (select auth.uid())
    )) and exists (
      select 1 from public.collaboration_requests cr
      where cr.id = request_id and cr.status = 'accepted'
    )
  );

create policy projects_participant_update on public.projects
  for update to authenticated using (
    brand_id = (select auth.uid()) or exists (
      select 1 from public.creator_profiles cp
      where cp.id = creator_id and cp.user_id = (select auth.uid())
    )
  ) with check (
    brand_id = (select auth.uid()) or exists (
      select 1 from public.creator_profiles cp
      where cp.id = creator_id and cp.user_id = (select auth.uid())
    )
  );

-- 2. Policies for project_tasks
